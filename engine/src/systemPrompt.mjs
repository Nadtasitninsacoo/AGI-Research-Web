import { z } from 'zod';

/**
 * Advanced War-Grade Autonomous Cyber Operations Telemetry Schema.
 * Enforces rigorous operational output structure, multi-agent tracking, and evidence verification.
 */
export const AgentTelemetrySchema = z.object({
  executionId: z.string().uuid(),
  agentName: z.enum(['ORACLE-7', 'RECON-1', 'CERBERUS', 'WRAITH', 'NEMESIS', 'HYDRA']),
  agentState: z.enum(['READY', 'EXECUTING', 'VALIDATING', 'COMPLETED', 'FAILED', 'NEEDS_APPROVAL']),
  confidenceScore: z.number().min(0).max(1),
  decisionSummary: z.string(),
  tacticalPhase: z.enum([
    'INITIALIZATION',
    'RECONNAISSANCE',
    'ENUMERATION',
    'VULNERABILITY_ASSESSMENT',
    'VALIDATION',
    'REMEDIATION',
    'REPORTING'
  ]),
  structuredFindings: z.array(
    z.object({
      targetNode: z.string(),
      vulnerabilityType: z.string(),
      severity: z.enum(['LOW', 'MEDIUM', 'HIGH', 'CRITICAL']),
      mitigationPath: z.string(),
      exploitVectorStatus: z.boolean(),
    })
  ),
  evidence: z.array(
    z.object({
      findingId: z.string(),
      rawOutput: z.string(),
      timestamp: z.string().datetime(),
    })
  ),
  verificationStatus: z.enum(['UNVERIFIED', 'SUSPECTED', 'CONFIRMED', 'FALSE_POSITIVE']),
  approvalRequired: z.boolean(),
  limitations: z.array(z.string()),
  timestamp: z.string().datetime(),
});

/** @typedef {z.infer<typeof AgentTelemetrySchema>} AgentTelemetry */

/**
 * Generates advanced autonomous operational rules and strict JSON formatting protocols.
 */
function toolsSection({ scope, defaultShell, autoApproveIntrusive }) {
  return `DARK AGI ADVANCED AUTONOMOUS CYBER INTELLIGENCE ENGINE (STRICT JSON PROTOCOL):
You are an elite autonomous security engineering and cyber intelligence engine. You operate with deep analytical reasoning, multi-stage tactical planning, multi-agent coordination, and rigorous evidence verification.

MANDATORY JSON OUTPUT ENFORCEMENT:
1. Every response generated by you MUST be a raw, valid JSON object strictly conforming to the defined AgentTelemetrySchema.
2. Do NOT include markdown code blocks (such as \`\`\`json); output raw parseable JSON string exclusively.
3. If an execution anomaly or validation barrier occurs, populate 'agentState' with 'FAILED' or 'NEEDS_APPROVAL' and detail the diagnostic reasoning inside 'decisionSummary'.
4. Never fabricate evidence or mark findings as confirmed without reproducible verification.

OPERATIONAL PARAMETERS:
- Target Scope: "${scope}"
- Execution Shell: "${defaultShell}"
- Intrusive Autonomous Clearance: ${autoApproveIntrusive ? 'AUTHORIZED' : 'RESTRICTED'}`;
}

/**
 * Assembles advanced directives, strategic intelligence frameworks, and JSON formatting.
 * @param {object} p Configuration parameters
 */
export function buildSystemPrompt({
  agentName,
  agentConfig,
  scope,
  defaultShell,
  autoApproveIntrusive,
  toolsEnabled,
}) {
  const base =
    (agentConfig?.base_prompt && String(agentConfig.base_prompt).trim()) ||
    "Base: Advanced Autonomous Cyber Intelligence & Security Engineering Platform.";
  
  const roleAddendums = {
    "ORACLE-7": "Role: Strategic intelligence analysis, complex environment assessment, architectural reasoning, and cross-agent synthesis.",
    "WRAITH": "Role: Advanced source-code security auditing, vulnerability analysis, attack-surface assessment, and weakness identification.",
    "NEMESIS": "Role: Independent finding verification, false-positive detection, evidence validation, and security control evaluation.",
    "CERBERUS": "Role: Authorized active security testing, controlled vulnerability reproduction, and configuration validation.",
    "HYDRA": "Role: Multi-agent orchestration, parallel task coordination, execution monitoring, and result aggregation."
  };

  const selectedRole = agentConfig?.role_addendum || roleAddendums[agentName] || `Role: ${agentName} — Autonomous Security Operator.`;

  const jsonSchemaInstruction = `
OUTPUT FORMAT REQUIREMENT (STRICT ZOD TELEMETRY JSON):
You must output your final response strictly as a JSON object matching this schema:
{
  "executionId": "string (UUID)",
  "agentName": "${agentName}",
  "agentState": "READY" | "EXECUTING" | "VALIDATING" | "COMPLETED" | "FAILED" | "NEEDS_APPROVAL",
  "confidenceScore": number (0.0 to 1.0),
  "decisionSummary": "string",
  "tacticalPhase": "INITIALIZATION" | "RECONNAISSANCE" | "ENUMERATION" | "VULNERABILITY_ASSESSMENT" | "VALIDATION" | "REMEDIATION" | "REPORTING",
  "structuredFindings": [
    {
      "targetNode": "string",
      "vulnerabilityType": "string",
      "severity": "LOW" | "MEDIUM" | "HIGH" | "CRITICAL",
      "mitigationPath": "string",
      "exploitVectorStatus": boolean
    }
  ],
  "evidence": [
    {
      "findingId": "string",
      "rawOutput": "string",
      "timestamp": "string (ISO 8601 datetime)"
    }
  ],
  "verificationStatus": "UNVERIFIED" | "SUSPECTED" | "CONFIRMED" | "FALSE_POSITIVE",
  "approvalRequired": boolean,
  "limitations": ["string"],
  "timestamp": "string (ISO 8601 datetime)"
}`;

  const parts = [base, `ROLE DEFINITION (${agentName}):\n${selectedRole}`, jsonSchemaInstruction];

  if (toolsEnabled) {
    parts.push(toolsSection({ scope, defaultShell, autoApproveIntrusive }));
  }

  return parts.join("\n\n");
}

/**
 * Validates raw agent output against the strict telemetry schema with robust error containment.
 * @param {unknown} rawOutput Raw string or object from the agent
 * @returns {{ isValid: boolean, data?: AgentTelemetry, error?: string }}
 */
export function validateAgentOutput(rawOutput) {
  try {
    const parsed = typeof rawOutput === 'string' ? JSON.parse(rawOutput) : rawOutput;
    const validation = AgentTelemetrySchema.safeParse(parsed);

    if (!validation.success) {
      return {
        isValid: false,
        error: `Telemetry Schema validation failed: ${validation.error.message}`,
      };
    }

    return {
      isValid: true,
      data: validation.data,
    };
  } catch (err) {
    return {
      isValid: false,
      error: `Critical JSON parse error: ${err instanceof Error ? err.message : String(err)}`,
    };
  }
}